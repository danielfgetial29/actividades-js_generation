// Operador Asignacion -> = "Este objeto ahora es igual a esto" ej: let x = 6;
// Comparacion -> == "Es este objeto igual a esto" ej x == 5;
// Comparacion estyricta -> === "Estrictamente de valor y tipo" ej x === 5;

let x = 5;

console.log("--- COMPARACIONES ---");
// Igual
console.log(x == 5);
console.log(x == 10);
// Mayor
console.log(x > 3);
// Menor
console.log(x < 3);
// Mayor e igual
console.log(x >= 5);
// Menor e igual
console.log(x <= 5);
// Diferente de
console.log(x != 10);
console.log();

//Modulo
console.log(10 % 3); //1 impar
console.log(10 % 5); //0 par
console.log(11 % 2); //1 impar
console.log(15 % 2);
console.log();

// Comparaciones estrictas
console.log();
console.log(5 == "5");
console.log(5 === "5");
